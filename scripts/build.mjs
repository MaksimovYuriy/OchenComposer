import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const names = {
  'Книга': 'book', 'Телефон': 'phone', 'Монета': 'coin', 'Пазлы': 'puzzle',
  'Цветы': 'flowers', 'Ручка': 'pen', 'Папка': 'folder', 'Наушники': 'headphones',
  'Лампа': 'lamp', 'Кошелек': 'wallet',
};
const assets = [];
for (const [folder, role] of [['mainground', 'main'], ['background', 'background']]) {
  for (const size of ['large', 'small']) {
    const directory = `assets/${folder}/${size}`;
    for (const file of (await readdir(new URL(`../${directory}/`, import.meta.url))).sort()) {
      if (!file.endsWith('.svg')) continue;
      const name = file.slice(0, -4);
      if (!names[name]) throw new Error(`Нет стабильного ID для ${directory}/${file}`);
      const source = `${directory}/${file}`;
      const svg = await readFile(new URL(`../${source}`, import.meta.url), 'utf8');
      const box = svg.match(/viewBox="([^"]+)"/)?.[1].trim().split(/[\s,]+/).map(Number);
      if (!box || box.length !== 4 || !box.every(Number.isFinite) || box[0] !== 0 || box[1] !== 0 || box[2] <= 0 || box[3] <= 0) {
        throw new Error(`Некорректный viewBox: ${source}`);
      }
      if (/<(?:image|script|foreignObject)\b|\bon\w+\s*=|(?:href\s*=\s*["'](?!#))|url\(\s*["']?(?!#)[a-z]/i.test(svg)) {
        throw new Error(`Неподдерживаемый или внешний ресурс: ${source}`);
      }
      const ids = new Set([...svg.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]));
      for (const match of svg.matchAll(/url\(#([^\)]+)\)/g)) {
        if (!ids.has(match[1])) throw new Error(`Не найден #${match[1]}: ${source}`);
      }
      assets.push({ id: names[name], name, role, size, source, width: box[2], height: box[3], svg });
    }
  }
}
for (const id of Object.values(names)) {
  if (assets.filter(asset => asset.id === id).length !== 4) throw new Error(`Неполный комплект вариантов: ${id}`);
  for (const size of ['large', 'small']) {
    const main = assets.find(a => a.id === id && a.size === size && a.role === 'main');
    const background = assets.find(a => a.id === id && a.size === size && a.role === 'background');
    if (main.width !== background.width || main.height !== background.height) throw new Error(`Размеры состояний различаются: ${id}/${size}`);
  }
}
await mkdir(new URL('../generated/', import.meta.url), { recursive: true });
const backdrops = [];
for (const size of ['large', 'small']) {
  const svg = await readFile(new URL(`../assets/colors/${size}/Фон.svg`, import.meta.url), 'utf8');
  const box = svg.match(/viewBox="([^"]+)"/)?.[1].trim().split(/[\s,]+/).map(Number);
  if (!box || box.length !== 4 || !box.every(Number.isFinite) || box[2] <= 0 || box[2] !== box[3]) throw new Error(`Некорректный квадратный фон: ${size}`);
  backdrops.push({ size, svg, width: box[2], height: box[3] });
}
await writeFile(new URL('../generated/assets.ts', import.meta.url),
  `// Generated by scripts/build.mjs; edit original SVG files instead.\nconst ASSETS: Asset[] = ${JSON.stringify(assets)};\nconst BACKDROPS: Backdrop[] = ${JSON.stringify(backdrops)};\n`);
execFileSync(process.execPath, [fileURLToPath(new URL('../node_modules/typescript/bin/tsc', import.meta.url)), '-p', 'tsconfig.json'], { cwd: root, stdio: 'inherit' });
console.log(`Упаковано ${assets.length} SVG, ${Object.keys(names).length} предметов. code.js готов.`);
